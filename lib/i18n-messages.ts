type Messages = (typeof messages)[Locale];

/**
 * Catalog lookup without React.
 *
 * This module carries no "use client" directive on purpose: server components
 * (reports, dashboard, finance) cannot call `useI18n`, and importing this catalog
 * from a client-marked module turns `getMessages` into a client reference that
 * the server is not allowed to invoke. Those pages read the locale from the
 * cookie instead - see `lib/i18n-server.ts`.
 */
export type { Messages };

export function getMessages(locale: Locale): Messages {
  return messages[locale];
}

/** Must match the name written by `I18nProvider` and read by `lib/i18n-server.ts`. */
export const LOCALE_COOKIE = "ims-locale";

/** Anything other than an explicit `en` cookie falls back to the app default, Arabic. */
export function resolveLocale(value: string | undefined | null): Locale {
  return value === "en" ? "en" : "ar";
}
